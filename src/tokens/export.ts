function setPath(obj: Record<string, any>, path: string[], value: unknown) {
  let o = obj;
  for (let i = 0; i < path.length - 1; i++) {
    const k = path[i];
    if (typeof o[k] !== 'object' || o[k] === null || '$value' in o[k]) {
      // A token and a group share a name (e.g. button.primary.bg and button.primary.bg.hover):
      // keep the token under "_" so the tree stays valid.
      const existing = o[k];
      o[k] = existing && '$value' in existing ? { _: existing } : {};
    }
    o = o[k];
  }
  const last = path[path.length - 1];
  if (o[last] && typeof o[last] === 'object' && !('$value' in o[last])) o[last]._ = value;
  else o[last] = value;
}

const DTCG_TYPE: Record<string, string> = { color: 'color', dimension: 'dimension', number: 'number', fontFamily: 'fontFamily', fontWeight: 'fontWeight', duration: 'duration', easing: 'cubicBezier', shadow: 'shadow', string: 'string' };

function resolvedModes(theme: ThemeDoc, id: string, platform?: Platform, app?: AppId) {
  const o = { platform, app, density: theme.density };
  return {
    light: resolveToken(theme, id, { appearance: 'light', ...o }),
    dark: resolveToken(theme, id, { appearance: 'dark', ...o }),
    lightHighContrast: resolveToken(theme, id, { appearance: 'light', contrast: 'high', ...o }),
    darkHighContrast: resolveToken(theme, id, { appearance: 'dark', contrast: 'high', ...o }),
  };
}

/** Structured, portable JSON (W3C Design Tokens–style, with `$value` references in `{token.id}` form). */
export function toJSON(theme: ThemeDoc, source: ThemeDoc = theme): string {
  const merged = mergedValues(theme);
  const tree: Record<string, any> = {};
  for (const d of TOKENS) {
    const value = merged[d.id];
    const entry: Record<string, unknown> = {
      $type: DTCG_TYPE[d.type],
      $value: isModal(value) ? { ...value } : value,
      ...(d.description ? { $description: d.description } : {}),
      $extensions: {
        'mercantile.layer': d.layer,
        'mercantile.category': d.category,
        'mercantile.group': d.group,
        ...(d.scale ? { 'mercantile.scales-with': d.scale } : {}),
        'mercantile.resolved': resolvedModes(theme, d.id),
        ...(theme.values[d.id] !== undefined ? { 'mercantile.modified': true } : {}),
      },
    };
    setPath(tree, [d.layer, ...d.id.split('.')], entry);
  }
  const platforms: Record<string, Record<string, unknown>> = {};
  for (const p of PLATFORMS) {
    if (p === 'web') continue;
    const ids = new Set([...Object.keys(PLATFORM_DEFAULTS[p]), ...Object.keys(theme.platforms[p] ?? {})]);
    platforms[p] = Object.fromEntries([...ids].map((id) => [id, { $value: rawValue(theme, id, { platform: p }), resolved: resolveToken(theme, id, { appearance: 'light', platform: p, density: theme.density }) }]));
  }
  const apps: Record<string, unknown> = {};
  for (const a of APP_IDS) {
    const ids = new Set([...Object.keys(APPS[a].overrides), ...Object.keys(theme.apps[a] ?? {})]);
    apps[a] = { label: APPS[a].label, overrides: Object.fromEntries([...ids].map((id) => [id, { $value: rawValue(theme, id, { app: a }), resolved: resolvedModes(theme, id, undefined, a) }])) };
  }
  return JSON.stringify(
    {
      $schema: 'https://design-tokens.github.io/community-group/format/',
      $description: `${theme.name}: Mercantile design tokens. Generated by ${GENERATOR}. Layers: foundation (primitives) → semantic (roles) → component (mappings). Applications must reference semantic and component tokens, never foundation values directly.`,
      meta: { name: theme.name, generator: GENERATOR, generatedAt: stamp(), density: theme.density, densityFactor: DENSITY_FACTOR[theme.density], modes: ['light', 'dark', 'lightHighContrast', 'darkHighContrast'], platforms: PLATFORMS, referenceSyntax: '{token.id}' },
      tokens: tree,
      platforms,
      apps,
      /** Re-importable form: only the overrides relative to the Mercantile defaults. */
      mercantile: { id: source.id, name: source.name, description: source.description, density: source.density, values: source.values, modes: source.modes, platforms: source.platforms, apps: source.apps },
    },
    null,
    2,
  );
}

