const camel = (parts: string[]) =>
  parts
    .map((p, i) => {
      const clean = p.replace(/[^a-zA-Z0-9]/g, '');
      return i === 0 ? clean.charAt(0).toLowerCase() + clean.slice(1) : clean.charAt(0).toUpperCase() + clean.slice(1);
    })
    .join('')
    .replace(/^(\d)/, '_$1');

/** "color.text.primary" → "textPrimary"; "palette.neutral.700" → "neutral700". */
function swiftName(id: string, dropFirst = 1) {
  const parts = id.split('.').slice(dropFirst);
  const n = camel(parts.map((p, i) => (i > 0 && /^\d/.test(p) ? p : p)));
  return /^\d/.test(n) ? `_${n}` : n || camel(id.split('.'));
}

function swiftColor(css: string): string {
  const c = parseColor(css);
  if (!c) return 'Color.clear';
  const hex = toHex(c).slice(1);
  return c.a < 1 ? `Color(hex: 0x${hex}, opacity: ${+c.a.toFixed(3)})` : `Color(hex: 0x${hex})`;
}

function toPoints(css: string): number | null {
  const m = /^(-?\d*\.?\d+)(px|pt|in|em|rem|)$/.exec(css.trim());
  if (!m) return null;
  const n = parseFloat(m[1]);
  if (m[2] === 'in') return n * 72;
  if (m[2] === 'rem') return n * 16;
  return n;
}

const num = (n: number) => (Number.isInteger(n) ? `${n}` : `${+n.toFixed(3)}`);

function swiftWeight(w: string) {
  const n = parseInt(w, 10);
  return n >= 800 ? '.heavy' : n >= 700 ? '.bold' : n >= 600 ? '.semibold' : n >= 500 ? '.medium' : n >= 400 ? '.regular' : n >= 300 ? '.light' : '.thin';
}

/** First family in a CSS stack as a Swift Font.custom name, or "" for Apple system faces. */
function swiftFamily(stack: string) {
  const first = stack.split(',')[0].trim().replace(/^["']|["']$/g, '');
  const system = ['-apple-system', 'BlinkMacSystemFont', 'system-ui', 'SF Pro', 'SF Pro Text', 'SF Pro Display', 'New York', 'SF Mono', 'ui-monospace', 'serif', 'sans-serif', 'monospace'];
  return system.includes(first) ? '' : first;
}

function swiftDesign(family: string) {
  const f = family.toLowerCase();
  return f.includes('mono') || f.includes('menlo') || f.includes('courier') ? '.monospaced' : f.includes('serif') && !f.includes('sans-serif') ? '.serif' : '.default';
}

function parseShadow(css: string) {
  if (!css || css === 'none') return null;
  // First layer only: "x y blur color"
  const first = css.split(/,(?![^(]*\))/)[0].trim();
  const m = /^(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+([\d.]+)(?:px)?\s+(.+)$/.exec(first);
  if (!m) return null;
  return { x: +m[1], y: +m[2], radius: +m[3] / 2, color: m[4] };
}

function swiftValueFor(theme: ThemeDoc, d: TokenDef, opts: { platform?: Platform; app?: AppId } = {}): string {
  const r = (appearance: 'light' | 'dark', contrast: 'standard' | 'high' = 'standard') => resolveToken(theme, d.id, { appearance, contrast, density: theme.density, ...opts });
  switch (d.type) {
    case 'color': {
      const l = r('light');
      const dk = r('dark');
      const hl = r('light', 'high');
      const hd = r('dark', 'high');
      if (l === dk && hl === l && hd === dk) return swiftColor(l);
      if (hl === l && hd === dk) return `Color(light: ${swiftColor(l)}, dark: ${swiftColor(dk)})`;
      return `Color(light: ${swiftColor(l)}, dark: ${swiftColor(dk)}, highContrastLight: ${swiftColor(hl)}, highContrastDark: ${swiftColor(hd)})`;
    }
    case 'dimension': {
      const p = toPoints(r('light'));
      return p === null ? `0 /* ${r('light')} */` : num(p);
    }
    case 'number':
      return num(parseFloat(r('light')) || 0);
    case 'fontWeight':
      return `Font.Weight${swiftWeight(r('light'))}`;
    case 'duration':
      return num((parseFloat(r('light')) || 0) / 1000);
    case 'easing': {
      const v = r('light');
      const m = /cubic-bezier\(([^)]+)\)/.exec(v);
      const pts = m ? m[1].split(',').map((x) => num(parseFloat(x))) : ['0', '0', '1', '1'];
      return `EasingCurve(${pts[0]}, ${pts[1]}, ${pts[2]}, ${pts[3]})`;
    }
    case 'shadow': {
      const s = parseShadow(r('light'));
      const sd = parseShadow(r('dark'));
      return s ? `ShadowToken(color: Color(light: ${swiftColor(s.color)}, dark: ${swiftColor(sd?.color ?? s.color)}), radius: ${num(s.radius)}, x: ${num(s.x)}, y: ${num(s.y)})` : 'ShadowToken.none';
    }
    case 'fontFamily':
      return `FontFamily(design: ${swiftDesign(r('light'))}, cssStack: ${JSON.stringify(r('light'))})`;
    default:
      return JSON.stringify(r('light'));
  }
}

