function mdValue(theme: ThemeDoc, id: string) {
  const v = mergedValues(theme)[id];
  const res = resolvedModes(theme, id);
  const raw = isModal(v) ? `light \`${v.light}\` · dark \`${v.dark}\`` : `\`${v}\``;
  const resolved = res.light === res.dark ? `\`${res.light}\`` : `\`${res.light}\` / \`${res.dark}\``;
  return { raw, resolved };
}

function tokenTable(theme: ThemeDoc, list: TokenDef[], withRaw = true) {
  const rows = list.map((d) => {
    const { raw, resolved } = mdValue(theme, d.id);
    return `| \`${d.id}\` | ${withRaw ? `${raw} | ` : ''}${resolved} | ${(d.description ?? '').replace(/\|/g, '\\|')} |`;
  });
  return `| Token | ${withRaw ? 'Defined as | ' : ''}Resolved (light / dark) | Purpose |\n|---|${withRaw ? '---|' : ''}---|---|\n${rows.join('\n')}\n`;
}

export function toMarkdown(theme: ThemeDoc, audit?: { label: string; mode: string; ratio: number; pass: boolean; min: number }[][]): string {
  const by = (pred: (d: TokenDef) => boolean) => TOKENS.filter(pred);
  const groups = (list: TokenDef[]) => {
    const m = new Map<string, TokenDef[]>();
    list.forEach((d) => {
      if (!m.has(d.group)) m.set(d.group, []);
      m.get(d.group)!.push(d);
    });
    return [...m.entries()];
  };
  let md = `# ${theme.name}: Mercantile Design System\n\n`;
  md += `> Generated by ${GENERATOR} on ${stamp()}. This document is the source of truth for visual decisions in every Mercantile application: web, macOS, iPhone and iPad.\n\n`;
  md += `## Instructions for building a Mercantile application\n\n`;
  md += `When building or modifying any application in this family:\n\n`;
  md += `1. **Use tokens, never raw values.** Reference semantic tokens (\`color.text.primary\`, \`space.component.default\`, \`radius.control\`) or component tokens (\`button.primary.bg\`). Do not hard-code hex colors, pixel sizes, font sizes, or durations. Foundation tokens (\`palette.*\`, \`space.1–12\`, \`font.size.*\`) exist only to define semantic tokens.\n`;
  md += `2. **Load the token file for the platform.** Web: include \`mercantile-tokens.css\` and use \`var(--token-name)\` (dots become hyphens: \`color.text.primary\` → \`--color-text-primary\`). SwiftUI: add \`MercantileTokens.swift\` and use \`Mercantile.Colors.textPrimary\`, \`MercantileText.body.font\`, \`Mercantile.Component.buttonPrimaryBg\`.\n`;
  md += `3. **Support light and dark appearance and increased contrast.** Every color token carries both appearances; high-contrast variants exist where needed. Never assume a light background.\n`;
  md += `4. **Respect platform conventions.** Use native navigation patterns: sidebars and inspectors on macOS and iPad, navigation stacks and tab bars on iPhone, responsive layouts on the web. Platform overrides already adjust type sizes, control heights and radii.\n`;
  md += `5. **Accessibility is required.** Meet WCAG 2.2 AA contrast (4.5:1 text, 3:1 large text and UI). Never use color alone: pair status color with an icon or symbol and a word. Show a visible focus ring (\`color.focus.ring\`). Touch targets are at least \`size.touch.min\` (44 pt). Honor Dynamic Type and Reduce Motion.\n`;
  md += `6. **Character.** Understated, traditional, refined, practical. Restrained corner radii, hairline borders instead of heavy shadows, no gradients, no oversized controls, no decoration that carries no information.\n`;
  md += `7. **Application accents.** An application may override only the \`color.accent.*\` family (see Application accents below). Everything else stays shared.\n\n`;
  md += `## Token architecture\n\n| Layer | Count | Purpose |\n|---|---|---|\n| Foundation | ${by((d) => d.layer === 'foundation').length} | Raw primitives: palette, scales, durations |\n| Semantic | ${by((d) => d.layer === 'semantic').length} | Purpose-based roles with light/dark values |\n| Component | ${by((d) => d.layer === 'component').length} | Per-component mappings to semantic tokens |\n\nReferences use \`{token.id}\` syntax. Theme density: **${theme.density}** (×${DENSITY_FACTOR[theme.density]} on spacing and control sizes).\n\n`;
  md += `## Color\n\n### Foundation palette\n\n${tokenTable(theme, by((d) => d.group === 'Palette / Foundation'), false)}\n`;
  md += `### Semantic colors\n\n${tokenTable(theme, by((d) => d.layer === 'semantic' && d.category === 'color'))}\n`;
  md += `### Chart palettes\n\nUse **categorical** for unordered series (max 8; beyond that, group as "Other"), **sequential** for ordered magnitude, and **diverging** for variance around a meaningful midpoint. Use \`color.chart.positive\` / \`negative\` for favorable and unfavorable variance. Always label series directly or with a legend, and use dash patterns or markers when series could be confused.\n\n${tokenTable(theme, by((d) => d.category === 'chart'), false)}\n`;
  md += `## Typography\n\n| Style | Family | Size (web / macOS / iOS) | Weight | Line height | Tracking | Purpose |\n|---|---|---|---|---|---|---|\n`;
  for (const s of TEXT_STYLES) {
    const r = (p: string, pf?: Platform) => resolveToken(theme, `text.${s}.${p}`, { appearance: 'light', platform: pf });
    const fam = (theme.values[`text.${s}.family`] ?? TOKEN_MAP.get(`text.${s}.family`)!.value) as string;
    md += `| \`text.${s}\` | ${fam.replace(/[{}]/g, '').replace('font.family.', '')} | ${r('size')} / ${r('size', 'macos')} / ${r('size', 'ios')} | ${r('weight')} | ${r('leading')} | ${r('tracking')} | ${TOKEN_MAP.get(`text.${s}.family`)?.description ?? ''} |\n`;
  }
  md += `\nFont stacks:\n\n${by((d) => d.id.startsWith('font.family')).map((d) => `- \`${d.id}\`: ${resolveToken(theme, d.id, { appearance: 'light' })}`).join('\n')}\n\nNumbers in tables, KPIs and statements use tabular lining figures (\`text.numeric.features\`).\n\n`;
  for (const [title, pred] of [
    ['Spacing & layout', (d: TokenDef) => d.category === 'spacing'],
    ['Shape, borders & elevation', (d: TokenDef) => d.category === 'shape' || d.category === 'elevation'],
    ['Icons', (d: TokenDef) => d.category === 'icon'],
    ['Motion', (d: TokenDef) => d.category === 'motion'],
  ] as const) {
    md += `## ${title}\n\n`;
    for (const [g, list] of groups(by(pred))) md += `### ${g}\n\n${tokenTable(theme, list)}\n`;
  }
  md += `Motion rules: hover and focus transitions use \`motion.duration.hover\`; elements entering use \`motion.easing.enter\`; sheets use \`motion.duration.page\`. With Reduce Motion on, all durations become 0 except loading indicators, which pulse instead of spinning.\n\nIcons: one line-icon family (SF Symbols natively; Lucide on the web) at \`icon.size.*\` with stroke \`icon.stroke.width\`. Icons that act as buttons always have an accessible label.\n\n`;
  md += `## Components\n\nComponent tokens map each component to semantic roles. Restyle a component by changing its component tokens, not the semantic tokens it uses.\n\n`;
  for (const [g, list] of groups(by((d) => d.layer === 'component'))) md += `### ${g}\n\n${tokenTable(theme, list)}\n`;
  md += `### Required interaction states\n\nEvery interactive component defines: default, hover (pointer platforms), pressed, focused (visible ring), selected, disabled (\`opacity.disabled\`), loading (spinner and \`aria-busy\`), success, and error (color plus icon plus message).\n\n`;
  md += `## Platform overrides\n\n`;
  for (const p of PLATFORMS) {
    if (p === 'web') continue;
    const ids = [...new Set([...Object.keys(PLATFORM_DEFAULTS[p]), ...Object.keys(theme.platforms[p] ?? {})])];
    md += `### ${PLATFORM_LABELS[p]}\n\n| Token | Web | ${PLATFORM_LABELS[p]} |\n|---|---|---|\n${ids.map((id) => `| \`${id}\` | ${resolveToken(theme, id, { appearance: 'light' })} | ${resolveToken(theme, id, { appearance: 'light', platform: p })} |`).join('\n')}\n\n`;
  }
  md += `## Application accents\n\n| Application | Accent (light / dark) |\n|---|---|\n${APP_IDS.map((a) => `| ${APPS[a].label} | ${resolveToken(theme, 'color.accent.default', { appearance: 'light', app: a })} / ${resolveToken(theme, 'color.accent.default', { appearance: 'dark', app: a })} |`).join('\n')}\n\n`;
  md += `## Reports & print\n\nPrinted documents use white paper and ink regardless of screen appearance. US Letter, \`report.page.margin\` margins, serif headings (\`report.heading.family\`), ${resolveToken(theme, 'report.body.size', { appearance: 'light' })} body text, hairline row rules, a strong rule under table headers, a single rule above subtotals, and a double rule under grand totals. Negatives appear in parentheses. Every page has a running header and a footer with "Page n of N". Charts use the print palette with dash patterns and no animation.\n\n`;
  if (audit) {
    const flat = audit.flat();
    const fails = flat.filter((x) => !x.pass);
    md += `## Accessibility audit\n\n${flat.length - fails.length} of ${flat.length} contrast checks pass WCAG AA across light, dark and high-contrast modes.\n\n`;
    if (fails.length) md += `| Pair | Mode | Ratio | Required |\n|---|---|---|---|\n${fails.map((f) => `| ${f.label} | ${f.mode} | ${f.ratio.toFixed(2)} | ${f.min} |`).join('\n')}\n\n`;
  }
  md += `## Changes from the Mercantile defaults\n\n`;
  const changed = Object.keys(theme.values);
  md += changed.length ? changed.map((id) => `- \`${id}\`: ${JSON.stringify(theme.values[id])}`).join('\n') + '\n' : 'None. This theme uses the default Mercantile values.\n';
  return md;
}

export function download(filename: string, content: string, type = 'text/plain') {
  const blob = new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

