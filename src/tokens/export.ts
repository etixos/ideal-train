const toCssValue = (s: string) => s.replace(/\{([^}]+)\}/g, (_, id: string) => `var(${cssVarName(id)})`);

function cssFor(d: TokenDef, raw: string, densityFactor: number) {
  let out = toCssValue(raw);
  if (d.scale === 'density' && densityFactor !== 1) {
    out = isPureRef(raw) || /px$/.test(raw.trim()) ? `calc(${out} * ${densityFactor})` : out;
  }
  return out;
}

function block(selector: string, lines: string[], indent = '') {
  if (!lines.length) return '';
  return `${indent}${selector} {\n${lines.map((l) => `${indent}  ${l}`).join('\n')}\n${indent}}\n`;
}

/** CSS custom properties. References are kept as var() so the cascade preserves the token graph. */
export function toCSS(theme: ThemeDoc): string {
  const merged = mergedValues(theme);
  const f = DENSITY_FACTOR[theme.density];
  const light: string[] = [];
  const dark: string[] = [];
  const hcLight: string[] = [];
  const hcDark: string[] = [];
  let lastLayer = '';
  for (const d of TOKENS) {
    if (d.layer !== lastLayer) {
      light.push(`/* ── ${d.layer} ── */`);
      lastLayer = d.layer;
    }
    const v = merged[d.id];
    const name = cssVarName(d.id);
    light.push(`${name}: ${cssFor(d, pickMode(v, { appearance: 'light' }), f)};`);
    if (isModal(v)) {
      if (v.dark !== v.light) dark.push(`${name}: ${cssFor(d, v.dark, f)};`);
      if (v.hcLight) hcLight.push(`${name}: ${cssFor(d, v.hcLight, f)};`);
      if (v.hcDark || v.dark !== v.light) hcDark.push(`${name}: ${cssFor(d, v.hcDark ?? v.dark, f)};`);
    }
  }
  const scope = (p: Platform | AppId, kind: 'platform' | 'app') => {
    const lines: string[] = [];
    const ids = kind === 'platform' ? new Set([...Object.keys(PLATFORM_DEFAULTS[p as Platform]), ...Object.keys(theme.platforms[p as Platform] ?? {})]) : new Set([...Object.keys(APPS[p as AppId].overrides), ...Object.keys(theme.apps[p as AppId] ?? {})]);
    const darkLines: string[] = [];
    for (const id of ids) {
      const d = TOKEN_MAP.get(id)!;
      const v = kind === 'platform' ? rawValue(theme, id, { platform: p as Platform }) : rawValue(theme, id, { app: p as AppId });
      if (v === undefined) continue;
      lines.push(`${cssVarName(id)}: ${cssFor(d, pickMode(v, { appearance: 'light' }), kind === 'platform' ? 1 : f)};`);
      if (isModal(v) && v.dark !== v.light) darkLines.push(`${cssVarName(id)}: ${cssFor(d, v.dark, f)};`);
    }
    return { lines, darkLines };
  };
  let css = `/*\n * ${theme.name}: Mercantile design tokens as CSS custom properties\n * Generated by ${GENERATOR} on ${stamp()}\n *\n * Appearance: light by default; dark follows prefers-color-scheme unless\n * [data-theme="light"] is set, or is forced with [data-theme="dark"].\n * Increased contrast: [data-contrast="high"] or prefers-contrast: more.\n * Platforms: [data-platform="macos|ios|ipados"]. Apps: [data-app="…"].\n * Density: ${theme.density} (×${f}) is baked into spacing and control sizes.\n */\n\n`;
  css += block(':root', light);
  css += `\n@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', dark, '  ')}}\n`;
  css += block(':root[data-theme="dark"]', dark);
  css += `\n@media (prefers-contrast: more) {\n${block(':root:not([data-contrast="standard"])', hcLight, '  ')}}\n`;
  css += block(':root[data-contrast="high"]', hcLight);
  css += block(':root[data-theme="dark"][data-contrast="high"]', hcDark);
  css += `\n@media (prefers-reduced-motion: reduce) {\n  :root {\n${TOKENS.filter((d) => d.type === 'duration' && d.id !== 'motion.duration.spin').map((d) => `    ${cssVarName(d.id)}: 0ms;`).join('\n')}\n  }\n}\n`;
  for (const p of PLATFORMS) {
    if (p === 'web') continue;
    const { lines } = scope(p, 'platform');
    css += `\n/* ${PLATFORM_LABELS[p]} overrides */\n` + block(`[data-platform="${p}"]`, lines);
  }
  for (const a of APP_IDS) {
    const { lines, darkLines } = scope(a, 'app');
    if (!lines.length) continue;
    css += `\n/* ${APPS[a].label} accent */\n` + block(`[data-app="${a}"]`, lines) + block(`[data-theme="dark"] [data-app="${a}"], [data-theme="dark"][data-app="${a}"]`, darkLines);
  }
  return css;
}

